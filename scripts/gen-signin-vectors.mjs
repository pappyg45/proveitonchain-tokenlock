// Dev only: regenerate test/fixtures/signin-vectors.json (cross-language sign-in and local-pass tests).
//   npm run build && node scripts/gen-signin-vectors.mjs
// Throwaway keys and secrets; nothing here unlocks anything real.
import { writeFileSync } from 'node:fs';
import { secp256k1 } from '@noble/curves/secp256k1.js';
import { sha256 } from '@noble/hashes/sha2.js';
import * as SV from '../dist/self-verify.js';

const msgHash = (m) => { const b = Buffer.from(m, 'utf8'); const l = b.length < 253 ? Buffer.from([b.length]) : Buffer.from([253, b.length & 255, b.length >> 8]); return sha256(sha256(Buffer.concat([Buffer.from('\x18Bitcoin Signed Message:\n'), l, b]))); };
const legacy = (priv, m, base) => { const s = secp256k1.sign(msgHash(m), priv, { prehash: false, format: 'recovered' }); return Buffer.concat([Buffer.from([base + s[0]]), Buffer.from(s.slice(1))]).toString('base64'); };
const now = Date.parse('2026-11-18T18:00:00.000Z');
const record = { v: 1, nonce: '0123456789abcdef0123456789abcdef', site: 'https://shop.example', assets: ['GOTPROOF'], any_name: true, issued_at: new Date(now).toISOString(), expires_at: new Date(now + 600e3).toISOString(), pass_ttl_s: 900 };
const message = SV.buildMessage(record);
const seedA = Buffer.from('a1'.repeat(32), 'hex'), seedB = Buffer.from('b2'.repeat(32), 'hex');
const pubA = secp256k1.getPublicKey(seedA, true), pubB = secp256k1.getPublicKey(seedB, true);
const A = SV._addr.p2wpkh(pubA), B = SV._addr.p2tr(pubB);
const SECRET = 'fixture-pass-secret-'.padEnd(40, 'x');
const pass = SV.issuePass({ sub: A, h: ['GOTPROOF'], k: 'key_a', n: record.nonce, s: record.site, i: now, e: now + 300e3 }, SECRET);
const out = {
  note: 'Generated by scripts/gen-signin-vectors.mjs with throwaway keys. For tests only.',
  now, record, message, pass_secret: SECRET,
  signers: [
    { address: A, kind: 'p2wpkh legacy h39', signature: legacy(seedA, message, 39) },
    { address: B, kind: 'p2tr legacy h31', signature: legacy(seedB, message, 31) },
  ],
  node_pass: { token: pass, address: A, key_id: 'key_a', expires_at: new Date(now + 300e3).toISOString() },
};
for (const s of out.signers) if (!SV.verifyMessageSignature(s.address, message, s.signature)) throw new Error('self-check failed ' + s.kind);
writeFileSync(new URL('../test/fixtures/signin-vectors.json', import.meta.url), JSON.stringify(out, null, 1) + '\n');
console.log('wrote signin-vectors.json');
